@dataclass(slots=True)
class I18n:
    language: str = "ru"

    def __post_init__(self) -> None:
        if self.language not in SUPPORTED_LANGUAGES:
            self.language = "en"

    def set_language(self, language: str) -> None:
        if language not in SUPPORTED_LANGUAGES:
            raise ValueError(f"Unsupported language: {language}")
        self.language = language

    def gettext(self, key: str, **kwargs: object) -> str:
        text = CATALOGS[self.language].get(key) or CATALOGS["en"].get(key) or key
        return text.format(**kwargs) if kwargs else text

    def category(self, category: DestinationCategory | str) -> str:
        value = category.value if isinstance(category, DestinationCategory) else str(category)
        return self.gettext(f"category.{value}")

    def confidence(self, confidence: ConfidenceLevel | str) -> str:
        value = confidence.value if isinstance(confidence, ConfidenceLevel) else str(confidence)
        return self.gettext(f"confidence.{value}")

    def status(self, status: OperationStatus | str) -> str:
        value = status.value if isinstance(status, OperationStatus) else str(status)
        return self.gettext(f"status.{value}")

    def detected_type(self, detected_type: DetectedType | str) -> str:
        value = detected_type.value if isinstance(detected_type, DetectedType) else str(detected_type)
        return self.gettext(f"type.{value}")


#: Windows primary language identifier for Russian (LANGID & 0x3FF).
_LANG_RUSSIAN = 0x19


def detect_default_language() -> str:
    """Pick the first-run UI language from the operating system.

    On Windows the user's display language is the authoritative signal
    (``LANG``/``LANGUAGE`` are normally unset there, which is why the old
    environment-variable check always answered "en"). Elsewhere, and as a
    fallback, the process locale and the usual environment variables are used.
    """
    ui_language = _windows_ui_language_id()
    if ui_language is not None:
        return "ru" if ui_language & 0x3FF == _LANG_RUSSIAN else "en"
    for candidate in _locale_candidates():
        text = candidate.lower()
        if text.startswith("ru") or "_ru" in text or "russian" in text:
            return "ru"
    return "en"


def _windows_ui_language_id() -> int | None:
    if not sys.platform.startswith("win"):
        return None
    try:
        import ctypes

        value = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        return value or None
    except Exception:
        return None


def _locale_candidates() -> list[str]:
    found: list[str] = []
    try:
        language, _encoding = locale.getlocale()
        if language:
            found.append(language)
    except Exception:
        pass
    for variable in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(variable)
        if value:
            found.append(value)
    return found


