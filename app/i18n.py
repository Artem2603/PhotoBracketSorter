@dataclass(slots=True)
class I18n:
    language: str = "ru"

    def __post_init__(self) -> None:
        if self.language not in SUPPORTED_LANGUAGES:
            self.language = "en"

    def set_language(self, language: str) -> None:
        if language not in SUPPORTED_LANGUAGES:
            raise ValueError(f"Unsupported language: {language}")
        self.language = language

    def gettext(self, key: str, **kwargs: object) -> str:
        text = CATALOGS[self.language].get(key) or CATALOGS["en"].get(key) or key
        return text.format(**kwargs) if kwargs else text

    def category(self, category: DestinationCategory | str) -> str:
        value = category.value if isinstance(category, DestinationCategory) else str(category)
        return self.gettext(f"category.{value}")

    def confidence(self, confidence: ConfidenceLevel | str) -> str:
        value = confidence.value if isinstance(confidence, ConfidenceLevel) else str(confidence)
        return self.gettext(f"confidence.{value}")

    def status(self, status: OperationStatus | str) -> str:
        value = status.value if isinstance(status, OperationStatus) else str(status)
        return self.gettext(f"status.{value}")

    def detected_type(self, detected_type: DetectedType | str) -> str:
        value = detected_type.value if isinstance(detected_type, DetectedType) else str(detected_type)
        return self.gettext(f"type.{value}")


def detect_default_language() -> str:
    lang, _encoding = locale.getdefaultlocale()
    if lang and lang.lower().startswith("ru"):
        return "ru"
    return "en"


def available_languages() -> tuple[str, ...]:
    return SUPPORTED_LANGUAGES


def translate_category(category: DestinationCategory | str, language: str = "ru") -> str:
    return I18n(language).category(category)


def format_status(status: OperationStatus | str, language: str = "ru") -> str:
    return I18n(language).status(status)


def validate_catalogs() -> tuple[bool, list[str]]:
    missing: list[str] = []
    reference = set(CATALOGS["en"])
    for language, catalog in CATALOGS.items():
        for key in reference:
            if key not in catalog:
                missing.append(f"{language}:{key}")
    for enum_value in DestinationCategory:
        for language in SUPPORTED_LANGUAGES:
            if f"category.{enum_value.value}" not in CATALOGS[language]:
                missing.append(f"{language}:category.{enum_value.value}")
    for enum_value in OperationStatus:
        for language in SUPPORTED_LANGUAGES:
            if f"status.{enum_value.value}" not in CATALOGS[language]:
                missing.append(f"{language}:status.{enum_value.value}")
    for enum_value in GroupClassification:
        for language in SUPPORTED_LANGUAGES:
            if f"group.{enum_value.value}" not in CATALOGS[language]:
                missing.append(f"{language}:group.{enum_value.value}")
    from app.review_queue import ReviewReason

    for enum_value in ReviewReason:
        for language in SUPPORTED_LANGUAGES:
            if f"reason.{enum_value.value}" not in CATALOGS[language]:
                missing.append(f"{language}:reason.{enum_value.value}")
    return not missing, missing


_DEFAULT = I18n("ru")


def t(key: str, **kwargs: object) -> str:
    return _DEFAULT.gettext(key, **kwargs)
